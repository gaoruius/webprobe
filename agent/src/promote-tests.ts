// Copy the valid regression tests from runs into BuggyShop's own test suite, where CI runs them.
//
//   npm run promote-tests -- runs/<id> [runs/<id> ...]
//
// Only tests gen-tests judged valid (fail with the bug, pass without it) are copied. Each lands in
// buggyshop/tests/regression/<name>.spec.ts, named after the bug the eval matched the report to,
// or the report's title for a bug the manifest doesn't know. A file that already exists is kept:
// someone may have reviewed or edited it. Review the diff before committing; that is the human
// step between "a model wrote this" and "this guards main".

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { liveBugs, score, type ExtraBug, type TruthBug } from "./eval.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const SHOP = path.join(here, "../../buggyshop");
const OUT = path.join(SHOP, "tests/regression");

type TestResult = { bug: number; title: string; file?: string; status: string };

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);

const runDirs = process.argv.slice(2);
if (runDirs.length === 0) {
  console.error("usage: npm run promote-tests -- runs/<id> [runs/<id> ...]");
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(path.join(SHOP, "bugs.manifest.json"), "utf8")) as {
  bugs: TruthBug[];
  extras?: ExtraBug[];
};
mkdirSync(OUT, { recursive: true });
let added = 0;

for (const dir of runDirs) {
  const testsJson = path.join(dir, "tests", "tests.json");
  if (!existsSync(testsJson)) {
    console.log(`${dir}: no tests yet (npm run gen-tests -- ${dir})`);
    continue;
  }
  const report = JSON.parse(readFileSync(path.join(dir, "report.json"), "utf8"));
  const { results } = JSON.parse(readFileSync(testsJson, "utf8")) as { results: TestResult[] };

  // Which bug each report is about, so two runs' tests for the same bug share one file name.
  const s = score(report.bugs, liveBugs(manifest.bugs, report.liveBugs ?? "all"), manifest.extras ?? []);
  const bugOf = new Map<number, string>();
  for (const x of [...s.found, ...s.duplicates, ...s.extras]) bugOf.set(x.report, x.id);

  for (const r of results) {
    if (r.status !== "valid" || !r.file) continue;
    const name = bugOf.get(r.bug - 1) ?? slug(r.title);
    const dest = path.join(OUT, `${name}.spec.ts`);
    if (existsSync(dest)) {
      console.log(`  keep   ${name}.spec.ts (already there)`);
      continue;
    }
    const code = readFileSync(path.join(dir, "tests", r.file), "utf8");
    const header = `// Regression test for: ${r.title}\n// Generated by WebProbe gen-tests from ${path.basename(dir)}, report #${r.bug}.\n// It failed with the bug and passed on the clean site. Edit freely; promote-tests won't overwrite it.\n\n`;
    writeFileSync(dest, header + code);
    added++;
    console.log(`  add    ${name}.spec.ts  ← ${r.title}`);
  }
}

console.log(`\n${added} new test(s) in ${path.relative(process.cwd(), OUT)}/. Review the diff, then commit.`);
